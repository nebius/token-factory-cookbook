import { notFound } from "next/navigation";
import { PrintButton } from "@/components/study/PrintButton";
import { getBySlug, getDiagrams, getThumbnail } from "@/lib/db/teardowns";
import { getNotes } from "@/lib/db/user";
import { categoryLabel } from "@/lib/schema/teardown";
import { isTestData } from "@/lib/provenance";
import styles from "./print.module.css";

export const dynamic = "force-dynamic";
export const metadata = { title: "Study sheet" };

const svgSrc = (svg: string) => `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;

export default async function PrintPage({ params, searchParams }: { params: Promise<{ slug: string }>; searchParams: Promise<{ v?: string }> }) {
  const { slug } = await params;
  const { v } = await searchParams;
  const t = getBySlug(slug, v ? Number(v) : undefined);
  if (!t?.meta) notFound();
  const { device, parts, systems, study } = t.meta;
  const notes = getNotes(slug);
  const diagrams = getDiagrams(t.id);
  const hasThumb = !!getThumbnail(t.id);
  const name = new Map(parts.map((p) => [p.id, p.name]));

  return (
    <main className={styles.sheet}>
      <PrintButton />
      <header className={styles.head}>
        <div>
          <div className={styles.eyebrow}>
            Cutaway study sheet · {categoryLabel(device.category)} · v{t.version}
          </div>
          <h1>{device.name}</h1>
          <p className={styles.summary}>{device.summary}</p>
          <p className={styles.small}>
            {parts.length} parts · {device.sizeMm.join(" × ")} mm · {isTestData(t.provider) ? "test fixture, not generated by Kimi" : "designed by Kimi K3.1 Pro"}
          </p>
        </div>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        {hasThumb && <img className={styles.thumb} src={`/api/thumb/${t.id}`} alt="" />}
      </header>

      <section>
        <h2>How it works</h2>
        <p>{study.overview}</p>
      </section>

      {study.keyConcepts.length > 0 && (
        <section>
          <h2>Key concepts</h2>
          <dl className={styles.dl}>
            {study.keyConcepts.map((c) => (
              <div key={c.title}>
                <dt>{c.title}</dt>
                <dd>{c.body}</dd>
              </div>
            ))}
          </dl>
        </section>
      )}

      {study.principles.length > 0 && (
        <section>
          <h2>Engineering principles</h2>
          <dl className={styles.dl}>
            {study.principles.map((c) => (
              <div key={c.title}>
                <dt>{c.title}</dt>
                <dd className={styles.mono}>{c.body}</dd>
              </div>
            ))}
          </dl>
        </section>
      )}

      {diagrams.map((d) => (
        <section key={d.kind} className={styles.diagram}>
          <h2>{d.title}</h2>
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={svgSrc(d.svg)} alt={d.title} />
        </section>
      ))}

      <section>
        <h2>Parts</h2>
        <table className={styles.table}>
          <thead>
            <tr>
              <th>#</th>
              <th>Part</th>
              <th>What it does</th>
              <th>Material</th>
            </tr>
          </thead>
          <tbody>
            {parts.map((p, i) => (
              <tr key={p.id}>
                <td>{i + 1}</td>
                <td>
                  <b>{p.name}</b>
                  {p.parentId && <div className={styles.small}>in {name.get(p.parentId)}</div>}
                </td>
                <td>
                  {p.function} {p.howItWorks}
                  {notes[p.id] && <div className={styles.note}>My note: {notes[p.id]}</div>}
                </td>
                <td>{p.material}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      {systems.length > 0 && (
        <section>
          <h2>Systems</h2>
          <dl className={styles.dl}>
            {systems.map((s) => (
              <div key={s.id}>
                <dt>
                  {s.name} <span className={styles.small}>({s.kind})</span>
                </dt>
                <dd>
                  {s.path.map((id) => name.get(id) ?? id).join(" → ")}. {s.explanation}
                </dd>
              </div>
            ))}
          </dl>
        </section>
      )}

      {study.glossary.length > 0 && (
        <section>
          <h2>Glossary</h2>
          <dl className={styles.glossary}>
            {study.glossary.map((g) => (
              <div key={g.term}>
                <dt>{g.term}</dt>
                <dd>{g.definition}</dd>
              </div>
            ))}
          </dl>
        </section>
      )}

      {study.quiz.length > 0 && (
        <section className={styles.breakBefore}>
          <h2>Check yourself</h2>
          <ol className={styles.quiz}>
            {study.quiz.map((q, i) => (
              <li key={i}>
                <b>{q.question}</b>
                <ol type="A">
                  {q.options.map((o) => (
                    <li key={o}>{o}</li>
                  ))}
                </ol>
              </li>
            ))}
          </ol>
          <h3>Answers</h3>
          <ol className={styles.small}>
            {study.quiz.map((q, i) => (
              <li key={i}>
                {String.fromCharCode(65 + q.answer)}. {q.explanation}
              </li>
            ))}
          </ol>
        </section>
      )}

      {notes[""] && (
        <section>
          <h2>My notes</h2>
          <p style={{ whiteSpace: "pre-wrap" }}>{notes[""]}</p>
        </section>
      )}

      <footer className={styles.small}>{device.disclaimer}</footer>
    </main>
  );
}
