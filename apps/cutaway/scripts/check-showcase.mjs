import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from '@playwright/test';
const base=process.env.BASE_URL??'http://127.0.0.1:5174';
const out=process.env.SCREENSHOTS??'qa';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],external=[];
const origin=new URL(base).origin;
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
page.on('request',r=>{if(/^https?:/.test(r.url())&&new URL(r.url()).origin!==origin)external.push(r.url())});
const shot=name=>page.screenshot({path:path.join(out,name+'.png')});
const loaded=async count=>{await page.getByRole('status').filter({hasText:`${count} parts loaded`}).waitFor({timeout:90000});await page.waitForTimeout(600)};
try{
 await page.goto(base);await loaded(47);
 assert.equal(await page.locator('canvas').count(),1);
 await shot('cutaway-engine');
 await page.locator('.all-parts button').first().click();
 assert.match(await page.locator('.selected-part').innerText(),/Nacelle Inlet Lip/);
 await page.getByRole('button',{name:'Clear selection',exact:true}).click();
 const slider=page.getByRole('slider',{name:'Take it apart',exact:true});
 await slider.focus();await slider.press('End');assert.equal(await slider.getAttribute('aria-valuenow'),'1');
 await page.waitForTimeout(400);await shot('cutaway-engine-exploded');
 await slider.press('Home');assert.equal(await slider.getAttribute('aria-valuenow'),'0');
 await page.getByRole('button',{name:'Slice',exact:true}).click();await page.getByRole('slider',{name:'Move the cut',exact:true}).waitFor();
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 assert.equal(await page.getByRole('slider',{name:'Move the cut',exact:true}).count(),0);
 await page.getByRole('button',{name:'See through',exact:true}).click();
 await page.getByRole('button',{name:'How it was built',exact:true}).click();assert.match(await page.locator('.how-built').innerText(),/makes no model calls/);
 await page.getByRole('button',{name:'Explore parts',exact:true}).click();
 await page.getByLabel('Choose a machine').selectOption('1');await loaded(34);await shot('cutaway-toothbrush');
 assert.equal(await page.locator('.all-parts button').count(),34);
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(500);await shot('cutaway-mobile');
 const bounds=await page.evaluate(()=>({width:innerWidth,doc:document.documentElement.scrollWidth,canvas:document.querySelector('canvas').getBoundingClientRect().width}));
 assert.ok(bounds.doc<=bounds.width,JSON.stringify(bounds));assert.equal(bounds.canvas,390);
 assert.equal(await page.getByAltText('Nebius Token Factory').evaluate(e=>e.complete&&e.naturalWidth>0),true);
 assert.match(await page.locator('footer').innerText(),/Amitesh Anand/);
 assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
 const result={passed:true,machines:[{parts:47,failed:0},{parts:34,failed:0}],desktop:'1440×900',mobile:'390×844',errors,external,checks:['all geometry builds','part selection','disassembly and reassembly','slice/reset','X-ray','walkthrough','machine switch','mobile overflow','logo and attribution','no external requests']};
 fs.writeFileSync(path.join(out,'showcase-results.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
}finally{await browser.close()}
