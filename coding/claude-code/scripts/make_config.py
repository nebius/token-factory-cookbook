"""Write litellm_config.yaml from the live Token Factory catalog.

    uv run --env-file .env python scripts/make_config.py

Reads TF_MAIN_MODEL, TF_FAST_MODEL and (optionally) TF_EXTRA_MODELS from the
environment, checks each ID against GET /v1/models?verbose=true, and writes one
LiteLLM route per model with the live context window and per-token prices, so
the proxy's cost tracking uses today's numbers instead of a bundled table.

It also writes claude_code.env with the context window Claude Code should
assume (see CONTEXT_CAP below); scripts/claude-tf.sh reads it.

No secret is written to either file: keys stay as `os.environ/...` references.
"""

from __future__ import annotations

import os
import pathlib
import sys

from tf_models import base_url, fetch_models, is_agent_capable, price_per_token

RECIPE_DIR = pathlib.Path(__file__).resolve().parent.parent
OUT = RECIPE_DIR / "litellm_config.yaml"
CLAUDE_ENV = RECIPE_DIR / "claude_code.env"

# Claude Code assumes 200,000 tokens for any model ID it does not recognise and
# compacts the conversation near that size. Some Token Factory models are
# smaller, and the API rejects an over-long prompt with HTTP 400, so the window
# is set to the smallest routed model, never above Claude Code's own default.
CONTEXT_CAP = 200_000


def wanted_ids() -> list[str]:
    ids: list[str] = []
    for var in ("TF_MAIN_MODEL", "TF_FAST_MODEL"):
        value = os.environ.get(var, "").strip()
        if not value:
            sys.exit(
                f"{var} is empty. Run scripts/list_models.py, pick a live model ID "
                f"and set {var} in .env."
            )
        ids.append(value)
    ids += [m.strip() for m in os.environ.get("TF_EXTRA_MODELS", "").split(",") if m.strip()]
    return list(dict.fromkeys(ids))  # de-duplicate, keep order


def route(model: dict) -> str:
    """One model_list entry. The proxy alias is the Token Factory ID itself."""
    lines = [
        f'  - model_name: "{model["id"]}"',
        "    litellm_params:",
        f'      model: "nebius/{model["id"]}"',
        # Released LiteLLM still defaults the nebius/ provider to the older
        # AI Studio host, so the Token Factory URL is set explicitly.
        f'      api_base: "{base_url()}"',
        "      api_key: os.environ/NEBIUS_API_KEY",
        "    model_info:",
        '      mode: "chat"',
        f"      max_input_tokens: {int(model['context_length'])}",
        f"      input_cost_per_token: {price_per_token(model, 'prompt'):.12f}",
        f"      output_cost_per_token: {price_per_token(model, 'completion'):.12f}",
    ]
    cached = price_per_token(model, "input_cache_read")
    if cached:
        lines.append(f"      cache_read_input_token_cost: {cached:.12f}")
    return "\n".join(lines)


def main() -> None:
    live = {m["id"]: m for m in fetch_models()}
    chosen = []
    for model_id in wanted_ids():
        model = live.get(model_id)
        if model is None:
            sys.exit(f"{model_id} is not in the live catalog. Run scripts/list_models.py.")
        if not is_agent_capable(model):
            sys.exit(f"{model_id} does not advertise tool calling; Claude Code cannot use it.")
        chosen.append(model)

    OUT.write_text(
        "# Generated by scripts/make_config.py from the live Token Factory catalog.\n"
        "# Re-run the script instead of editing: IDs, windows and prices change.\n"
        "model_list:\n"
        + "\n".join(route(m) for m in chosen)
        + "\n\nlitellm_settings:\n"
        "  # Claude Code sends Anthropic-only fields; drop what the upstream cannot take.\n"
        "  drop_params: true\n"
        "\ngeneral_settings:\n"
        "  master_key: os.environ/LITELLM_MASTER_KEY\n"
    )
    window = min(CONTEXT_CAP, *(int(m["context_length"]) for m in chosen))
    CLAUDE_ENV.write_text(
        "# Generated by scripts/make_config.py. Read by scripts/claude-tf.sh.\n"
        f"TF_CONTEXT_TOKENS={window}\n"
    )

    print(f"wrote {OUT.name} with {len(chosen)} route(s):")
    for m in chosen:
        print(f"  {m['id']}  (context {m['context_length']})")
    print(f"wrote {CLAUDE_ENV.name}: Claude Code will assume a {window}-token window")


if __name__ == "__main__":
    main()
